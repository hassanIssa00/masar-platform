export function getCurriculaForGrade(grade?: string): CurriculumSubject[] {
  if (!grade) return curriculaList;
  const g = grade.toLowerCase();
  if (g.includes('روضة') || g.includes('تمهيدي') || g.includes('kg')) return kgCurricula;
  if (g.includes('متوسط') || g.includes('إعدادي') || g.includes('middle')) return middleCurricula;
  if (g.includes('ثانوي') || g.includes('مسار') || g.includes('high')) return highCurricula;
  return curriculaList;
}

export function getAllCurricula(): CurriculumSubject[] {
  return [...curriculaList, ...kgCurricula, ...middleCurricula, ...highCurricula];
}

export function getCurriculumBySlug(slug: string): CurriculumSubject | undefined {
  return getAllCurricula().find((c) => c.slug === slug);
}
