function lowerQuestions(prefix: PlacementGradeKey, shift: number) {
  return lowerCore.map((question, index) => ({
    ...question,
    id: `${prefix}_${question.id}`,
    prompt:
      shift === 0
        ? question.prompt
        : index % 5 === 0
          ? `${question.prompt} اختر الإجابة بدقة.`
          : question.prompt,
  }));
}

