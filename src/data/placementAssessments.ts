function upperQuestions(prefix: PlacementGradeKey, level: number) {
  return upperCore.map((question, index) => ({
    ...question,
    id: `${prefix}_${question.id}`,
    prompt:
      level === 4
        ? question.prompt
        : index % 3 === 0
          ? `${question.prompt} هذا سؤال مستوى ${level}.`
          : question.prompt,
  }));
}

